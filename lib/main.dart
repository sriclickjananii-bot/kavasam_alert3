import 'package:flutter/material.dart';
import 'package:firebase_core/firebase_core.dart';
import 'theme/app_theme.dart';
import 'screens/permission_screen.dart';
import 'screens/sos_alert_screen.dart';
import 'models/sos_packet.dart';
import 'services/alert_service.dart';
import 'services/app_lang.dart';
import 'services/notification_service.dart';
import 'services/sos_bridge.dart';
import 'services/storage_service.dart';
import 'services/location_share_service.dart';

final GlobalKey<NavigatorState> navigatorKey = GlobalKey<NavigatorState>();

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();

  // Requires firebase_options.dart generated by `flutterfire configure`
  // (see README.md "Firebase setup"). Wrapped in try/catch so the rest
  // of the app (BLE/SMS/auto-call) still works even before you've set
  // up Firebase for the live-location feature.
  // identity used by the native service to talk to the backend
  await StorageService().ensureResponderCredentials();
  await AppLang.load(); // one language for the whole app

  try {
    await Firebase.initializeApp();
    // continue always-on location sharing if the user left it on
    LocationShareService.instance.resumeIfEnabled();
  } catch (e) {
    debugPrint('Firebase not configured yet — live location sharing '
        'will be unavailable until you run `flutterfire configure`. ($e)');
  }

  // Reopens the full-screen SOS alert if the user taps the emergency
  // notification instead of already being on that screen (e.g. the
  // notification fired while the app was in the background).
  await NotificationService.instance.init(
    onSosNotificationTapped: (payload) {
      if (SosBridge.alertOpen) return;
      navigatorKey.currentState?.push(
        MaterialPageRoute(
          builder: (_) => SosAlertScreen(
            packet: SosPacket(
              packetType: 0x01,
              gpsFixValid: payload.gpsFixValid,
              buttonHeld: true,
              latitude: payload.latitude,
              longitude: payload.longitude,
            ),
            source: payload.source,
          ),
          fullscreenDialog: true,
        ),
      );
    },
  );

  runApp(const KavasamAlertApp());

  // SOS received by the background BLE service (works even when the app
  // was closed or the phone was locked): open the full-screen alert.
  await SosBridge.init(onSos: _openDeviceSos);
}

void _openDeviceSos(Map<String, dynamic> m) {
  if (SosBridge.alertOpen) return;
  final numbers = List<String>.from(m['numbers'] as List? ?? const []);
  final sent = List<String>.from(m['sent'] as List? ?? const []);
  final failed = List<String>.from(m['failed'] as List? ?? const []);

  final packet = SosPacket(
    packetType: 0x01,
    gpsFixValid: m['hasLocation'] as bool? ?? false,
    buttonHeld: true,
    latitude: (m['lat'] as num?)?.toDouble() ?? 0,
    longitude: (m['lon'] as num?)?.toDouble() ?? 0,
    emergencyNumbers: numbers,
  );

  final nav = navigatorKey.currentState;
  if (nav == null) {
    // Cold start: the UI isn't built yet — retry after the first frame.
    WidgetsBinding.instance.addPostFrameCallback((_) => _openDeviceSos(m));
    return;
  }
  nav.push(
    MaterialPageRoute(
      builder: (_) => SosAlertScreen(
        packet: packet,
        source: m['fromSms'] == true
            ? 'sms'
            : (m['fromResponder'] == true ? 'nearby' : 'device'),
        victimName: m['name'] as String?,
        distanceM: (m['distance'] as num?)?.toInt(),
        alertRef: m['ref'] as String?,
        nearRegistered: m['atRegistered'] == true,
        preDispatched: AlertDispatchResult(
          succeededNumbers: sent,
          failedNumbers: failed,
        ),
      ),
      fullscreenDialog: true,
    ),
  );
}

class KavasamAlertApp extends StatelessWidget {
  const KavasamAlertApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      navigatorKey: navigatorKey,
      title: 'Kavasam Alert 3',
      debugShowCheckedModeBanner: false,
      theme: AppTheme.theme,
      builder: (context, child) {
        final mq = MediaQuery.of(context);
        // Scale every hard-coded font size to the phone's width and ignore
        // an oversized system font / display zoom, so text always fits.
        final w = mq.size.width;
        final double fit = (w / 411.0).clamp(0.8, 1.0).toDouble();
        final double sys = mq.textScaler.scale(1.0).clamp(0.8, 1.0).toDouble();
        return MediaQuery(
          data: mq.copyWith(textScaler: TextScaler.linear(fit * sys)),
          child: child ?? const SizedBox.shrink(),
        );
      },
      home: const StartupGate(),
    );
  }
}